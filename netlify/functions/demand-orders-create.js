'use strict';

const { requireAuth } = require('./_lib/auth');
const { getSupabase } = require('./_lib/supabase');
const { greenToCherry } = require('./_lib/cherryConversion');
const { bogotaToday, daysBetween } = require('./_lib/bogotaTime');
const { PROCESS_TYPES, PHYSICAL_ASPECTS } = require('./_lib/schema');
const { created, badReq, conflict, serverErr, methodNotAllowed, parseJson } = require('./_lib/respond');

const ORDER_TYPES = ['Spot', 'Contract', 'FOB'];
const REGIONS     = ['USA', 'EU', 'UK', 'MENA', 'AU'];

/**
 * POST /demand-orders-create  (forest, admin)
 * Body:
 *   reference_id            uuid
 *   variety_ids             [uuid]
 *   kg_green_required       number > 0
 *   max_delivery_date       'YYYY-MM-DD'
 *   physical_aspect         one of PHYSICAL_ASPECTS
 *   process_type            one of PROCESS_TYPES
 *   fermentation_hours      number >= 0 (optional)
 *   comments                string (optional)
 *   override_15_day         boolean (required true if delivery <15 days)
 *
 *   order_type              'Spot' | 'Contract' | 'FOB' (optional)
 *   client_name             string (optional)
 *   regions                 [string] subset of {USA, EU, UK, MENA, AU} (optional)
 *   contract_code           string (optional)
 */
exports.handler = requireAuth(['forest', 'admin'], async (event, _ctx, session) => {
  if (event.httpMethod !== 'POST') return methodNotAllowed(['POST']);
  let body;
  try { body = parseJson(event); } catch (e) { return badReq(e.message, e.code); }

  const errors = [];
  const reference_id = body.reference_id;
  const variety_ids  = Array.isArray(body.variety_ids) ? body.variety_ids : [];
  const kg_green_required = Number(body.kg_green_required);
  const max_delivery_date = body.max_delivery_date;
  const physical_aspect   = body.physical_aspect;
  const process_type      = body.process_type;
  const fermentation_hours = body.fermentation_hours == null ? null : Number(body.fermentation_hours);
  const comments         = body.comments == null ? null : String(body.comments);
  const override_15_day  = !!body.override_15_day;

  // New commercial metadata
  const order_type   = body.order_type   == null ? null : String(body.order_type);
  const client_name  = body.client_name  == null ? null : String(body.client_name).trim() || null;
  const regions      = Array.isArray(body.regions) ? body.regions.filter(Boolean) : null;
  const contract_code = body.contract_code == null ? null : String(body.contract_code).trim() || null;

  if (!reference_id) errors.push('reference_id required');
  if (!Number.isFinite(kg_green_required) || kg_green_required <= 0) errors.push('kg_green_required must be > 0');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(max_delivery_date || '')) errors.push('max_delivery_date must be YYYY-MM-DD');
  if (!PHYSICAL_ASPECTS.includes(physical_aspect)) errors.push('physical_aspect invalid');
  if (!PROCESS_TYPES.includes(process_type)) errors.push('process_type invalid');
  if (fermentation_hours != null && (!Number.isFinite(fermentation_hours) || fermentation_hours < 0))
    errors.push('fermentation_hours must be >= 0');
  if (order_type != null && !ORDER_TYPES.includes(order_type)) errors.push('order_type invalid');
  if (regions && !regions.every((r) => REGIONS.includes(r))) errors.push('regions must be subset of USA/EU/UK/MENA/AU');
  if (errors.length) return badReq(errors.join('; '), 'VALIDATION_ERROR');

  // 15-day rule
  const today = bogotaToday();
  const daysToDelivery = daysBetween(today, max_delivery_date);
  if (daysToDelivery < 15 && !override_15_day) {
    return conflict(
      'Max delivery date is less than 15 days away — confirmation with finca required.',
      'FIFTEEN_DAY_RULE',
      { days_to_delivery: daysToDelivery, requires_override: true }
    );
  }

  const sb = getSupabase();

  // Validate reference exists
  const { data: refRow, error: refErr } = await sb
    .from('coffee_references').select('id, name, active').eq('id', reference_id).maybeSingle();
  if (refErr) return serverErr('Reference lookup failed', refErr.message);
  if (!refRow || !refRow.active) return badReq('Unknown or inactive reference', 'INVALID_REFERENCE');

  // Insert order (order_code auto-generated by trigger)
  const { data: orderRow, error: insErr } = await sb
    .from('demand_orders').insert({
      reference_id,
      kg_green_required,
      max_delivery_date,
      physical_aspect,
      process_type,
      fermentation_hours,
      comments,
      override_15_day,
      order_type,
      client_name,
      regions: regions && regions.length > 0 ? regions : null,
      contract_code,
      created_by: session.role,
    }).select().single();
  if (insErr) return serverErr('Failed to create demand order', insErr.message);

  if (variety_ids.length > 0) {
    const rows = variety_ids.map((variety_id) => ({ demand_order_id: orderRow.id, variety_id }));
    const { error: vErr } = await sb.from('demand_order_varieties').insert(rows);
    if (vErr) return serverErr('Failed to link varieties', vErr.message);
  }

  // Notificacion: las creaciones de pedidos se acumulan en el daily
  // digest (scheduled daily-new-orders-digest), no se envia email
  // inmediato. Asi finca recibe un solo email por dia con todos los
  // pedidos del periodo en vez de uno por cada uno.

  return created({
    order: {
      ...orderRow,
      kg_cherry_required: greenToCherry(Number(orderRow.kg_green_required)),
    },
  });
});
